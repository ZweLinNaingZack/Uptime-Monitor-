// /monitors/123: one monitor's stats, chart and history.
//
// The folder name `[id]` makes this a DYNAMIC route: the part of the URL in that
// position arrives as `params.id`. Two things are new in this version of Next.js:
//
// 1. `params` is a Promise, not a plain object. You must await it (or use React's
//    `use()`), because Next.js may start rendering before it knows the URL.
// 2. With Cache Components, the id is only known at request time, so params count as
//    "runtime data", like an uncached fetch. Reading them must happen inside <Suspense>,
//    so the static parts (the back link) can be prerendered into the shell.

import type { Metadata } from "next";
import Link from "next/link";
import { notFound } from "next/navigation";
import { Suspense } from "react";

import MonitorDetail from "@/components/MonitorDetail";
import { ApiError, errorMessage } from "@/lib/api";
import { DEFAULT_PERIOD_HOURS, fetchMonitorDetail, type MonitorDetailData } from "@/lib/monitorDetail";

export const metadata: Metadata = {
  title: "Monitor · Uptime Monitor",
};

// `PageProps<"/monitors/[id]">` is generated by Next.js from the folder structure, so
// TypeScript knows `params` contains `id: string`.
export default function MonitorPage({ params }: PageProps<"/monitors/[id]">) {
  return (
    <div>
      <Link href="/" className="text-sm text-zinc-500 hover:underline">
        ← All monitors
      </Link>
      <div className="mt-4">
        <Suspense fallback={<DetailSkeleton />}>
          {/* Pass the params Promise down and await it inside the boundary. */}
          <MonitorDetailLoader params={params} />
        </Suspense>
      </div>
    </div>
  );
}

async function MonitorDetailLoader({ params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;

  // URL segments are always strings, and anyone can type /monitors/banana. Validate
  // before using it: notFound() renders the 404 page and stops rendering this component.
  // Note: because this runs inside a streamed <Suspense> boundary, the HTTP status line
  // ("200 OK") was already sent with the shell. Next.js adds <meta name="robots"
  // content="noindex"> instead, so search engines still treat it as a missing page.
  const monitorId = Number(id);
  if (!Number.isInteger(monitorId) || monitorId < 1) notFound();

  let data: MonitorDetailData | null = null;
  let error: string | null = null;
  try {
    data = await fetchMonitorDetail(monitorId, DEFAULT_PERIOD_HOURS);
  } catch (e) {
    if (e instanceof ApiError && e.status === 404) notFound();
    error = errorMessage(e); // backend down: let the client component show it and retry
  }

  return <MonitorDetail monitorId={monitorId} initialData={data} initialError={error} />;
}

function DetailSkeleton() {
  return (
    <div className="animate-pulse space-y-6" aria-busy="true" aria-label="Loading monitor">
      <div className="h-32 rounded-lg bg-zinc-200 dark:bg-zinc-800" />
      <div className="grid grid-cols-2 gap-4 sm:grid-cols-4">
        {[0, 1, 2, 3].map((i) => (
          <div key={i} className="h-24 rounded-lg bg-zinc-200 dark:bg-zinc-800" />
        ))}
      </div>
      <div className="h-64 rounded-lg bg-zinc-200 dark:bg-zinc-800" />
    </div>
  );
}
